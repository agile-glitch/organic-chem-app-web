// Build data/iupac_names.js: the systematic names js/name_suggest.js offers (simple molecules enumerated and named by the app's
// own namer). The list depends only on the namer (js/chem.js), so run this again after changing the namer.
//   python tools/serve.py &      node tools/build_iupac_names.js [http://localhost:8000/app.html]
// Needs Playwright (npm i playwright). PLAYWRIGHT_MODULE / CHROMIUM override where they are found.
const fs = require('fs'), path = require('path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const base = process.argv[2] || 'http://localhost:8000/app.html';
  const b = await chromium.launch({ executablePath: process.env.CHROMIUM || undefined, args: ['--no-sandbox'] });
  const p = await b.newPage();
  await p.route('**/data/iupac_names.js', r => r.fulfill({ status: 404, body: '' }));   // build from scratch, never from the old list
  await p.goto(base + '#sketcher', { waitUntil: 'load' });
  await p.waitForFunction(() => window.IupacGen, null, { timeout: 60000 });
  const t0 = Date.now();
  await p.evaluate(() => window.IupacGen.generate());
  await p.waitForFunction(() => window.IupacGen.ready, null, { timeout: 600000, polling: 500 });
  const list = await p.evaluate(() => window.IupacGen.names.map(n => [n.label, n.smiles]));
  await b.close();
  const out = path.join(__dirname, '..', 'data', 'iupac_names.js');
  fs.writeFileSync(out, '/* generated by tools/build_iupac_names.js from the app\'s IUPAC namer: do not edit by hand. [name, SMILES] */\n' +
    'window.IUPAC_NAMES=' + JSON.stringify(list) + ';\n');
  console.log(`wrote ${out}: ${list.length} names (${((Date.now() - t0) / 1000).toFixed(1)} s to name them; ${(fs.statSync(out).size / 1e6).toFixed(2)} MB)`);
})();
